"""Build the passphrase wordlist from the EFF large wordlist.

    python tools/make_wordlist.py

Downloads EFF's eff_large_wordlist.txt (7,776 words, one per five-dice roll),
checks it, and writes it to the one place that still picks passphrases:

    supabase/functions/admin-reset-passphrase/eff_large_wordlist.ts   the admin reset

Since 2 Nov 2026 new accounts use a 4-digit PIN, so the app no longer makes
passphrases and app/eff_large_wordlist.json is gone; the admin reset still gives
an older (passphrase) account four new words.

The list is by the Electronic Frontier Foundation. EFF's copyright page
(https://www.eff.org/copyright, checked 18 Oct 2026) puts its original material
under Creative Commons Attribution: the text says CC BY 4.0 International, and the
badge on the same page links to CC BY 3.0 US. Both ask for the same thing, credit
to EFF, so the attribution travels with both files and is repeated on privacy.html.
"""

import hashlib
import itertools
import json
import re
import sys
import urllib.request
from pathlib import Path

URL = 'https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt'
SOURCE_PAGE = 'https://www.eff.org/deeplinks/2016/07/new-wordlists-random-passphrases'
LICENCE = 'Creative Commons Attribution (CC BY), see https://www.eff.org/copyright'
ATTRIBUTION = 'EFF large wordlist, by the Electronic Frontier Foundation'

ROOT = Path(__file__).resolve().parent.parent
FN_OUT = ROOT / 'supabase' / 'functions' / 'admin-reset-passphrase' / 'eff_large_wordlist.ts'


def fail(msg):
    sys.exit('make_wordlist: ' + msg)


def main():
    with urllib.request.urlopen(URL, timeout=30) as resp:
        raw = resp.read().decode('utf-8')

    codes, words = [], []
    for line in raw.splitlines():
        line = line.strip()
        if not line:
            continue
        m = re.fullmatch(r'([1-6]{5})\s+(\S+)', line)
        if not m:
            fail(f'unexpected line: {line!r}')
        codes.append(m.group(1))
        words.append(m.group(2))

    # Exactly one word per dice roll 11111..66666, in order, all distinct.
    expected = [''.join(p) for p in itertools.product('123456', repeat=5)]
    if codes != expected:
        fail('the dice codes are not exactly 11111..66666 in order')
    if len(words) != 7776 or len(set(words)) != 7776:
        fail(f'expected 7776 distinct words, got {len(words)} ({len(set(words))} distinct)')
    bad = [w for w in words if not re.fullmatch(r'[a-z]+(-[a-z]+)*', w)]
    if bad:
        fail(f'words outside a-z / inner hyphen: {bad[:10]}')

    sha = hashlib.sha256(raw.encode('utf-8')).hexdigest()
    shortest = min(len(w) for w in words)
    print(f'{len(words)} words, shortest {shortest} letters, sha256 {sha}')

    FN_OUT.parent.mkdir(parents=True, exist_ok=True)
    body = ',\n'.join('  ' + json.dumps(w) for w in words)
    FN_OUT.write_text(
        '// GENERATED by tools/make_wordlist.py: do not edit by hand.\n'
        f'// {ATTRIBUTION}.\n'
        f'// Licence: {LICENCE}.\n'
        f'// Source: {URL} (sha256 {sha})\n'
        f'// About: {SOURCE_PAGE}\n'
        'export const WORDS: readonly string[] = [\n' + body + '\n];\n',
        encoding='utf-8', newline='\n')

    print(f'wrote {FN_OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
